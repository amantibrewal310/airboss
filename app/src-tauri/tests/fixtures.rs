/// The fixtures' "now": the design's "checked 10:44".
const FIXED_NOW: &str = "2026-11-25T10:44:00.000Z";

fn app_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn at(ago: Duration) -> String {
    time::to_ts(time::from_ts(FIXED_NOW).unwrap() - ago)
}

const MIN: u64 = 60;
const HOUR: u64 = 3600;
const DAY: u64 = 86_400;

fn secs(s: u64) -> Duration {
    Duration::from_secs(s)
}

/// Writes `text` to `path`, or with `AIRBOSS_FIXTURES_CHECK=1` checks it's already there.
fn write_or_check(path: &Path, text: &str) {
    if std::env::var("AIRBOSS_FIXTURES_CHECK").as_deref() == Ok("1") {
        let old = std::fs::read_to_string(path).unwrap_or_default();
        assert!(
            old == text,
            "{} is out of date: run `cargo test -p airboss-app --test fixtures`",
            path.display()
        );
    } else {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }
}

