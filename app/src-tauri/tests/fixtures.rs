//! Writes what the UI builds against, from real Rust output:
//! - `app/src/lib/types/generated/types.ts`: every type the UI sees, from ts-rs
//! - `app/src/lib/mock/fixtures/recorded.json`: the read fixtures, and each scripted write's
//!   `{command, args, response | error, events}` (the replay transport's `Recording`)
//!
//! The data is DESIGN's sample (`airboss_app::seed::design`) on the fakes. Times from `core`
//! are mapped to a fixed clock, so running it twice changes nothing. With
//! `AIRBOSS_FIXTURES_CHECK=1` it fails on any difference instead of writing (for CI).

