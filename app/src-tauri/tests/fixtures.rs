/// Maps every time `core` wrote during this run onto the fixed clock: times from the seed
/// become "now minus the task's design age", and times from the script become "now".
struct Clock {
    start: SystemTime,
    seed_end: SystemTime,
    ages: HashMap<i64, Duration>,
}

impl Clock {
    fn fix(&self, v: &mut Value, ctx: Option<i64>) {
        match v {
            Value::Object(map) => {
                let own = map
                    .get("task")
                    .and_then(Value::as_i64)
                    .or_else(|| {
                        (map.contains_key("title") || map.contains_key("status"))
                            .then(|| map.get("id").and_then(Value::as_i64))
                            .flatten()
                    })
                    .or(ctx);
                for (_, x) in map.iter_mut() {
                    self.fix(x, own);
                }
            }
            Value::Array(items) => items.iter_mut().for_each(|x| self.fix(x, ctx)),
            Value::String(s) => {
                let Some(t) = time::from_ts(s) else { return };
                if t + Duration::from_secs(1) < self.start {
                    return; // a fixed time we chose
                }
                let now = time::from_ts(FIXED_NOW).unwrap();
                *s = if t >= self.seed_end {
                    FIXED_NOW.to_string()
                } else {
                    let age = ctx
                        .and_then(|id| self.ages.get(&id).copied())
                        .unwrap_or(Duration::from_secs(3 * DAY));
                    time::to_ts(now - age)
                };
            }
            _ => {}
        }
    }
}

fn event_json(e: &UiEvent) -> Value {
    json!({ "event": e.name(), "payload": e.payload() })
}

#[test]
fn recorded_reads_and_scripted_writes() {
    let start = SystemTime::now();
    let app = TestApp::with_home(Store::open_in_memory().unwrap(), PathBuf::from("/Users/me"));
    let design = app.core(airboss_app::seed::design).unwrap();
    app.sync.set_snapshot(sync_snapshot());
    app.sync.set_connections(vec![
        Connection {
            name: "GitHub".into(),
            ok: true,
            state: "Signed in".into(),
            detail: "Pull requests sync every 5 minutes. A merged PR finishes its task.".into(),
            fix: None,
        },
        Connection {
            name: "T3 Code".into(),
            ok: true,
            state: "Live state".into(),
            detail: "Shows which agents are working or waiting on you.".into(),
            fix: None,
        },
    ]);
    app.launch.set_availability(Availability::Ready {
        version: "0.0.24".into(),
    });
    app.attention.set_items(needs(&design.proposals));
    app.attention.set_checked_at(Some(FIXED_NOW.into()));
    app.sync_vm();
    app.state.catch_up_services();
    let seed_end = SystemTime::now();
    std::thread::sleep(Duration::from_millis(5));
    app.shell.take_events();

    let mut reads = serde_json::Map::new();
    for (command, args) in [
        ("bootstrap", json!({})),
        ("quickadd_data", json!({})),
        ("t3_projects", json!({})),
        ("get_settings", json!({})),
        ("notification_permission", json!({})),
        ("plans", json!({ "req": 1 })),
        (
            "task_detail",
            json!({ "id": 142, "req": 1, "historyLimit": 30 }),
        ),
        ("run_map", json!({ "id": 200, "req": 1 })),
        ("update_status", json!({})),
    ] {
        let out = airboss_app::ipc::dispatch(&app.state, Caller::Main, command, args).unwrap();
        reads.insert(command.into(), out);
    }
    // The CLI check reads this machine's PATH; the fixture says what a fresh Mac would.
    reads["bootstrap"]["cli"]["on_path"] = json!(false);
    app.shell.take_events();

    let script_path = {
        let ui = app_dir().join("tests/script.json");
        if ui.exists() {
            ui
        } else {
            Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/script.json")
        }
    };
    let steps: Vec<Value> =
        serde_json::from_str(&std::fs::read_to_string(&script_path).unwrap()).unwrap();
    let mut script = Vec::new();
    for step in steps {
        let command = step["command"].as_str().unwrap().to_string();
        let args = step["args"].clone();
        let mut out = json!({ "command": command, "args": args.clone() });
        match airboss_app::ipc::dispatch(&app.state, Caller::Main, &command, args) {
            Ok(v) => out["response"] = v,
            Err(e) => out["error"] = serde_json::to_value(e).unwrap(),
        }
        out["events"] = Value::Array(app.shell.take_events().iter().map(event_json).collect());
        script.push(out);
    }

    let mut recording = json!({ "reads": reads, "script": script });
    Clock {
        start,
        seed_end,
        ages: design.ages.iter().map(|(k, v)| (k.0, *v)).collect(),
    }
    .fix(&mut recording, None);
    let text = format!("{}\n", serde_json::to_string_pretty(&recording).unwrap());
    write_or_check(
        &app_dir().join("src/lib/mock/fixtures/recorded.json"),
        &text,
    );

    // Sanity: the script ran as written (no step failed).
    assert!(
        recording["script"]
            .as_array()
            .unwrap()
            .iter()
            .all(|s| s.get("error").is_none()),
        "a scripted write failed"
    );
    let _ = Arc::strong_count(&app.state);
}
